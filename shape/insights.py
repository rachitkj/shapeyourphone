"""Read-only views that help the owner decide: usage suggestions and a shareable device report."""

from __future__ import annotations

import time
from typing import Callable, Dict, List, Optional

from . import __version__
from . import changes as ch
from . import plans, probe
from .adb import Device
from .state import PhoneState

HOUR = 3_600_000
DAY = 24 * HOUR


def _in_reach(cfg: dict) -> set:
    pkgs = set(cfg.get("dock", {}).get("apps", []))
    for w in cfg.get("home", []):
        if w.get("type") == "apps":
            pkgs |= set(w.get("apps", []))
    return {p.split("/")[0] for p in pkgs}


def suggest(usage: List[dict], cfg: dict, days: int, can_disable: Callable[[str], bool],
            is_system: Callable[[str], bool], now_ms: Optional[int] = None) -> Dict[str, List[dict]]:
    """Turn usage stats into suggestions. Nothing here changes the phone."""
    now_ms = now_ms or int(time.time() * 1000)
    reach = _in_reach(cfg)
    hidden = set(cfg.get("drawer", {}).get("hidden", [])) | set(cfg.get("drawer", {}).get("searchOnly", []))
    used = sorted((u for u in usage if u.get("foreground_ms", 0) > 0), key=lambda u: -u["foreground_ms"])

    def fmt(u: dict) -> dict:
        return {"package": u["package"], "label": u.get("label", u["package"]),
                "minutes_per_day": round(u.get("foreground_ms", 0) / days / 60000, 1)}

    dock = [fmt(u) for u in used if u["package"] not in reach and u["package"] not in hidden][:4]
    heavy = [fmt(u) for u in used if u["foreground_ms"] / days > HOUR and u["package"] not in hidden]
    unused = []
    for u in sorted(usage, key=lambda u: u.get("label", "").lower()):
        last = u.get("last_used", 0)
        if u["package"] in reach or u["package"] in hidden:
            continue
        if last and now_ms - last < days * DAY:
            continue
        item = fmt(u)
        item["last_used_days_ago"] = None if not last else round((now_ms - last) / DAY)
        if is_system(u["package"]):
            item["option"] = "disable with shape (reversible)" if can_disable(u["package"]) else "hide it in the launcher (shape protects this app)"
        else:
            item["option"] = "uninstall it, or hide it in the launcher"
        unused.append(item)
    return {"put_in_reach": dock, "heavy_use": heavy, "unused": unused}


def share_report(dev: Device, ps: PhoneState, launcher_status: Optional[dict]) -> str:
    """Anonymous markdown for a GitHub issue. No serials, ids, or the owner's own apps."""
    prof = probe.profile(dev)
    log = ch.ChangeLog(ps)
    bloat = plans.load_bloat()
    by_kind: Dict[str, Dict[str, int]] = {}
    for c in log.changes:
        by_kind.setdefault(c.kind, {"applied": 0, "undone": 0, "failed": 0})
        by_kind[c.kind][c.status] = by_kind[c.kind].get(c.status, 0) + 1

    def public(c: ch.Change) -> bool:
        # Only list targets that are public knowledge: bloat-list packages and setting keys.
        return (c.kind.startswith("package.") and c.target in bloat) or c.kind in ("setting", "nightmode", "home", "app.install")

    worked = sorted({c.target for c in log.changes if c.kind.startswith("package.") and c.status in ("applied", "undone") and c.target in bloat})
    failed = [c for c in log.changes if c.status == "failed"]
    lines = [
        "### Device report — shapeyourphone %s" % __version__,
        "",
        "| | |",
        "|---|---|",
        "| Phone | %s %s (`%s`) |" % (prof["manufacturer"], prof["model"], prof["device"]),
        "| Android | %s (SDK %s) |" % (prof["android"], prof["sdk"]),
        "| Skin | %s |" % prof["skin"],
        "| Security patch | %s |" % prof["security_patch"],
    ]
    if launcher_status is None:
        lines.append("| Launcher | not installed |")
    elif "error" in launcher_status:
        lines.append("| Launcher | installed, not answering: %s |" % launcher_status["error"])
    else:
        lines.append("| Launcher | v%s, default home: %s |" % (launcher_status.get("version"), "yes" if launcher_status.get("is_default_home") else "**no**"))
    lines += ["", "**Changes by kind** (applied / undone / failed)", ""]
    for kind, n in sorted(by_kind.items()):
        lines.append("- `%s`: %d / %d / %d" % (kind, n.get("applied", 0), n.get("undone", 0), n.get("failed", 0)))
    if worked:
        lines += ["", "**Bloat entries that worked here** (for `verified_on`):", ""]
        lines.append(", ".join("`%s`" % p for p in worked))
    if failed:
        lines += ["", "**Failures**", ""]
        for c in failed:
            target = c.target if public(c) else "(app %s)" % c.kind
            lines.append("- `%s` %s — %s" % (c.kind, target, (c.error or "").strip()[:200]))
    lines += ["", "<!-- Generated by `shape report --share`. Contains no serial numbers, account info or personal app list. -->"]
    return "\n".join(lines)
